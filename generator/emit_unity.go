package generator

import (
	"fmt"
	"sort"
	"strings"
)

// UnityOpts holds optional emission knobs.
type UnityOpts struct {
	// SettingsSizeAsserts is a C-type-name → expected sizeof(bytes) map.
	// For each entry, EmitUnity appends a _Static_assert at the end of the
	// unity .cpp file. If joltc/Jolt is rebuilt with a struct layout that
	// doesn't match the recorded size, the C++ build fails immediately
	// instead of silently producing memory-incorrect code.
	SettingsSizeAsserts map[string]int
}

// EmitUnity returns the unity-build .cpp content that compiles all of Jolt
// + joltc as one translation unit per platform.
func EmitUnity(joltSources, joltcSources []string, opts UnityOpts) string {
	var b strings.Builder
	b.WriteString("// Code generated by jolt-go generator. DO NOT EDIT.\n")
	b.WriteString("// Build aggregator: includes all Jolt and joltc translation units.\n\n")
	for _, p := range joltSources {
		fmt.Fprintf(&b, `#include "../../third_party/JoltPhysics/Jolt/%s"`+"\n", p)
	}
	for _, p := range joltcSources {
		fmt.Fprintf(&b, `#include "../../third_party/joltc/%s"`+"\n", p)
	}

	if len(opts.SettingsSizeAsserts) > 0 {
		b.WriteString("\n// ABI size guards — break the build if a Jolt struct layout drifts.\n")
		names := make([]string, 0, len(opts.SettingsSizeAsserts))
		for name := range opts.SettingsSizeAsserts {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			size := opts.SettingsSizeAsserts[name]
			fmt.Fprintf(&b, `_Static_assert(sizeof(%s) == %d, "%s layout drift");`+"\n", name, size, name)
		}
	}
	return b.String()
}
