// EmitJolt returns the source for jolt/jolt_generated.go.
func EmitJolt(h *Header) string {
	var b strings.Builder
	b.WriteString("// Code generated by jolt-go generator. DO NOT EDIT.\n\npackage jolt\n\n")
	b.WriteString(`import (
    "runtime"
    "unsafe"

    "github.com/gataengine/jolt-go/internal/cjolt"
)

// silence unused-import warnings until first use
var _ = unsafe.Sizeof(0)
var _ = runtime.GC

`)

	// Track which Go types have already been emitted as struct definitions.
	alreadyEmitted := map[string]bool{}

	// Emit Go-side aliases for integer typedefs (e.g. ObjectLayer = uint16).
	b.WriteString(emitTypedefs(h))

	// Pair Create/Destroy by type name and emit one OwnedType block per pair
	// that is *not* in the RefCounted set.
	pairs := pairCreateDestroy(h)
	for _, p := range pairs {
		if isRefCounted(p.GoType) {
			continue
		}
		b.WriteString(emitOwned(p))
		alreadyEmitted[p.GoType] = true
	}

	// Emit ref-counted type definitions and constructors.
	b.WriteString(emitRefCountedTypes(h))
	for _, name := range Annotations.RefCounted {
		alreadyEmitted[name] = true
	}

	// Emit plain handle wrappers for opaque structs not covered above.
	b.WriteString(emitPlainHandleTypes(h, alreadyEmitted))
	// Update alreadyEmitted with any new types from plain handle pass.
	for _, s := range h.Structs {
		if s.Opaque {
			goName := strings.TrimPrefix(s.Name, "JPH_")
			alreadyEmitted[goName] = true
		}
	}

	// Emit settings structs (Approach 1: layout-match Go struct + SetX setters).
	for _, s := range h.Structs {
		if s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if _, ok := Annotations.SettingsInit[goName]; !ok {
			continue
		}
		b.WriteString(emitSettingsType(s))
		alreadyEmitted[goName] = true
	}

	// Emit method bindings on receiver types.
	b.WriteString(emitReceiverMethods(h, alreadyEmitted))

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return b.String()
	}
	return string(out)
}

// ownedPair pairs a Create function with its matching Destroy function for an owned (non-ref-counted) type.
type ownedPair struct {
	GoType  string
	Create  Func
	Destroy Func
}

// pairCreateDestroy returns matched (Create, Destroy) function pairs from the header.
func pairCreateDestroy(h *Header) []ownedPair {
	creates := map[string]Func{}
	destroys := map[string]Func{}
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if !ok {
			continue
		}
		switch method {
		case "Create":
			creates[recv] = f
		case "Destroy":
			destroys[recv] = f
		}
	}
	var out []ownedPair
	for t, c := range creates {
		if d, ok := destroys[t]; ok {
			out = append(out, ownedPair{GoType: t, Create: c, Destroy: d})
		}
	}
	return out
}

// isRefCounted reports whether a type is in the RefCounted sidecar list.
func isRefCounted(t string) bool {
	return slices.Contains(Annotations.RefCounted, t)
}

// emitRefCountedTypes emits struct definitions for all RefCounted types
// (using Annotations.Inheritance for parents) and constructors with
// finalizer-registered Release for types that have a JPH_X_Create function.
func emitRefCountedTypes(h *Header) string {
	var b strings.Builder

	// 1. Type definitions for every RefCounted type.
	for _, name := range Annotations.RefCounted {
		if parent, ok := Annotations.Inheritance[name]; ok {
			// Embedded inheritance.
			fmt.Fprintf(&b, "type %s struct{ %s }\n", name, parent)
		} else {
			// Root of hierarchy (Shape, PhysicsMaterial) — holds the cjolt handle.
			fmt.Fprintf(&b, "type %s struct{ h *cjolt.C_JPH_%s }\n", name, name)
		}
	}
	b.WriteString("\n")

	// 2. Constructors for types that have a JPH_X_Create function.
	creates := map[string]Func{}
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if ok && method == "Create" && isRefCounted(recv) {
			creates[recv] = f
		}
	}
	// Emit in stable order: iterate Annotations.RefCounted to preserve declaration order.
	for _, goType := range Annotations.RefCounted {
		f, ok := creates[goType]
		if !ok {
			continue
		}
		b.WriteString(emitRefCountedConstructor(goType, f))
	}
	return b.String()
}

// emitRefCountedConstructor emits the public constructor and hidden finalizer
// for a single ref-counted type.
func emitRefCountedConstructor(goType string, f Func) string {
	var b strings.Builder

	// Build Go param signature and cjolt call arguments.
	var goParams []string
	var cjoltArgs []string
	for _, p := range f.Params {
		goName := safeParamName(p.Name)
		gt, callExpr := joltParamFromCType(p.CType, goName)
		goParams = append(goParams, goName+" "+gt)
		cjoltArgs = append(cjoltArgs, callExpr)
	}

	paramList := strings.Join(goParams, ", ")
	argList := strings.Join(cjoltArgs, ", ")

	fmt.Fprintf(&b, "func New%s(%s) *%s {\n", goType, paramList, goType)
	fmt.Fprintf(&b, "    h := cjolt.%s(%s)\n", f.Name, argList)
	chain := buildEmbeddedChain(goType)
	fmt.Fprintf(&b, "    s := &%s{%s}\n", goType, chain)
	fmt.Fprintf(&b, "    runtime.SetFinalizer(s, (*%s).finalize)\n", goType)
	fmt.Fprintf(&b, "    return s\n}\n\n")

	// finalize method — calls the root type's Release (walks up Inheritance to find root).
	root := rootRefCountedType(goType)
	fmt.Fprintf(&b, "func (s *%s) finalize() {\n", goType)
	fmt.Fprintf(&b, "    if s.h != nil {\n")
	fmt.Fprintf(&b, "        cjolt.JPH_%s_Release(s.h)\n", root)
	fmt.Fprintf(&b, "        s.h = nil\n")
	fmt.Fprintf(&b, "    }\n}\n\n")

	return b.String()
}

// joltParamFromCType maps a C type string to (goType, cjoltCallExpr) for use in
// the public jolt API.
func joltParamFromCType(cType, argName string) (goType, callExpr string) {
	s := strings.TrimPrefix(cType, "const ")
	s = strings.TrimSpace(s)
	// Pointer type: strip trailing '*'.
	if base, ok := strings.CutSuffix(s, "*"); ok {
		base = strings.TrimSpace(base)
		switch base {
		case "JPH_Vec3":
			return "Vec3", "(*cjolt.C_JPH_Vec3)(unsafe.Pointer(&" + argName + "))"
		case "JPH_Quat":
			return "Quat", "(*cjolt.C_JPH_Quat)(unsafe.Pointer(&" + argName + "))"
		case "JPH_RVec3":
			return "RVec3", "(*cjolt.C_JPH_RVec3)(unsafe.Pointer(&" + argName + "))"
		}
		// Other pointer: pass through opaque handle.
		return "*" + strings.TrimPrefix(base, "JPH_"), argName + ".h"
	}
	// Scalars — map to Go-native; no cast needed (cjolt wrapper already accepts Go-native).
	switch s {
	case "float":
		return "float32", argName
	case "double":
		return "float64", argName
	case "bool":
		return "bool", argName
	case "int", "int32_t":
		return "int32", argName
	case "unsigned int", "uint32_t":
		return "uint32", argName
	case "uint8_t":
		return "uint8", argName
	case "int8_t":
		return "int8", argName
	case "uint16_t":
		return "uint16", argName
	case "int16_t":
		return "int16", argName
	case "uint64_t":
		return "uint64", argName
	case "int64_t":
		return "int64", argName
	}
	// Unknown: pass through (will fail to compile for exotic types — Task 33).
	return s, argName
}

// rootRefCountedType walks up Annotations.Inheritance from goType to find
// the topmost ancestor (the type that holds the actual cjolt handle).
// For a root type with no parent, returns goType unchanged.
func rootRefCountedType(goType string) string {
	cur := goType
	for {
		parent, ok := Annotations.Inheritance[cur]
		if !ok {
			return cur
		}
		cur = parent
	}
}

// buildEmbeddedChain produces the struct literal initialiser for a ref-counted
// type with embedded parents, e.g.:
//
//	BoxShape    → "ConvexShape: ConvexShape{Shape: Shape{h: h}}"
//	ConvexShape → "Shape: Shape{h: h}"
//	Shape       → "h: h"
func buildEmbeddedChain(goType string) string {
	parent, ok := Annotations.Inheritance[goType]
	if !ok {
		// Root type: just the handle field.
		return "h: h"
	}
	return parent + ": " + parent + "{" + buildEmbeddedChain(parent) + "}"
}

// emitOwned emits the public Go API for one owned-type pair: type, constructor with finalizer, Close, finalize.
func emitOwned(p ownedPair) string {
	return fmt.Sprintf(`type %[1]s struct {
    h *cjolt.C_JPH_%[1]s
}

func New%[1]s() *%[1]s {
    p := &%[1]s{h: cjolt.JPH_%[1]s_Create()}
    runtime.SetFinalizer(p, (*%[1]s).finalize)
    return p
}

func (p *%[1]s) Close() error {
    if p.h != nil {
        cjolt.JPH_%[1]s_Destroy(p.h)
        p.h = nil
        runtime.SetFinalizer(p, nil)
    }
    return nil
}

func (p *%[1]s) finalize() { _ = p.Close() }

`, p.GoType)
}

// emitTypedefs emits Go-side aliases for joltc integer typedefs.
// e.g., "typedef uint16_t JPH_ObjectLayer" → "type ObjectLayer = uint16"
func emitTypedefs(h *Header) string {
	var b strings.Builder
	cToGo := map[string]string{
		"uint8_t":  "uint8",
		"int8_t":   "int8",
		"uint16_t": "uint16",
		"int16_t":  "int16",
		"uint32_t": "uint32",
		"int32_t":  "int32",
		"uint64_t": "uint64",
		"int64_t":  "int64",
		"float":    "float32",
		"double":   "float64",
	}
	// Sort for deterministic output.
	var aliases []string
	for k := range h.Typedefs {
		aliases = append(aliases, k)
	}
	sort.Strings(aliases)

	for _, alias := range aliases {
		underlying := h.Typedefs[alias]
		goType, ok := cToGo[underlying]
		if !ok {
			continue
		}
		goName := strings.TrimPrefix(alias, "JPH_")
		fmt.Fprintf(&b, "type %s = %s\n", goName, goType)
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

// emitSettingsType emits a Go struct mirroring a JPH_*Settings C struct (Approach 1).
// Every scalar/math field maps directly. Pointer fields become unexported uintptr
// slots with a SetX(*X) setter that stores via unsafe.Pointer + KeepAlive.
func emitSettingsType(s Struct) string {
	goName := strings.TrimPrefix(s.Name, "JPH_")
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", goName)

	type ptrSetter struct {
		Field string // "Shape"
		Type  string // "Shape" (without JPH_)
	}
	var pointerFields []ptrSetter

	for _, f := range s.Fields {
		cType := f.CType
		// Pointer fields become unexported uintptr slots and need setters.
		if strings.HasSuffix(cType, "*") {
			// e.g., "JPH_Shape *" → field "shape uintptr"
			pointerFields = append(pointerFields, ptrSetter{
				Field: f.Name,
				Type:  strings.TrimSpace(strings.TrimPrefix(strings.TrimSuffix(strings.TrimSpace(cType), "*"), "JPH_")),
			})
			// Lowercase first letter for the unexported slot.
			slotName := strings.ToLower(f.Name[:1]) + f.Name[1:]
			fmt.Fprintf(&b, "    %s uintptr\n", slotName)
			continue
		}
		// Map C type to Go type.
		goType := mapCFieldTypeToGo(cType)
		fmt.Fprintf(&b, "    %s %s\n", f.Name, goType)
	}
	b.WriteString("}\n\n")

	for _, p := range pointerFields {
		slotName := strings.ToLower(p.Field[:1]) + p.Field[1:]
		argName := strings.ToLower(p.Type[:1]) + p.Type[1:]
		fmt.Fprintf(&b, "func (s *%s) Set%s(%s *%s) {\n", goName, p.Field, argName, p.Type)
		fmt.Fprintf(&b, "    s.%s = uintptr(unsafe.Pointer(%s.h))\n", slotName, argName)
		fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", argName)
		b.WriteString("}\n\n")
	}
	return b.String()
}

// mapCFieldTypeToGo maps a C field type string to the corresponding Go type.
// JPH_Vec3 → Vec3, JPH_ObjectLayer → ObjectLayer (typedef alias),
// uint64_t → uint64, _Bool → bool, float → float32, etc.
func mapCFieldTypeToGo(cType string) string {
	cType = strings.TrimSpace(cType)
	// JPH_-prefixed types: strip the prefix; the type is defined either in math.go
	// (Vec3/Quat/...) or via emitTypedefs (ObjectLayer/MotionType) or as opaque struct.
	if strings.HasPrefix(cType, "JPH_") {
		return strings.TrimPrefix(cType, "JPH_")
	}
	// C scalars.
	cToGo := map[string]string{
		"uint8_t":  "uint8",
		"int8_t":   "int8",
		"uint16_t": "uint16",
		"int16_t":  "int16",
		"uint32_t": "uint32",
		"int32_t":  "int32",
		"uint64_t": "uint64",
		"int64_t":  "int64",
		"float":    "float32",
		"double":   "float64",
		"bool":     "bool",
		"_Bool":    "bool",
	}
	if goT, ok := cToGo[cType]; ok {
		return goT
	}
	// Unknown type: pass through (likely fails compile in Task 33).
	return cType
}

// mathReturnTypes is the set of Go math types that require the unsafe.Pointer
// cast pattern when returned from cjolt functions.
var mathReturnTypes = map[string]bool{
	"Vec3": true, "Quat": true, "Mat44": true,
	"RVec3": true, "RMat44": true,
}

// skipMethods lists C method names that are handled by dedicated emitters and
// must not be turned into receiver methods.
var skipMethods = map[string]bool{
	"Create":   true,
	"Destroy":  true,
	"AddRef":   true,
	"Release":  true,
	"Init":     true,
	"SetProcs": true,
}

// emitPlainHandleTypes emits "type Foo struct{ h *cjolt.C_JPH_Foo }" for each
// opaque struct that doesn't have a Create/Destroy pair (Owned) and isn't
// in the RefCounted set.
func emitPlainHandleTypes(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, s := range h.Structs {
		if !s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		fmt.Fprintf(&b, "type %s struct{ h *cjolt.C_JPH_%s }\n\n", goName, goName)
	}
	return b.String()
}

// emitReceiverMethods walks Funcs and emits Go methods on receiver types for
// functions matching JPH_<Recv>_<Method> where the first param is the receiver.
func emitReceiverMethods(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if !ok {
			continue
		}
		if skipMethods[method] {
			continue
		}
		if len(f.Params) == 0 {
			continue
		}

		// Verify the first param is a receiver (self) for this type.
		// recv is already without JPH_ prefix (SplitMethod strips it).
		// C type looks like "JPH_Body *" or "const JPH_Body *".
		firstParam := f.Params[0]
		stripped := strings.TrimPrefix(firstParam.CType, "const ")
		stripped = strings.TrimSpace(stripped)
		// The C type retains the JPH_ prefix; recv does not.
		expectedPtr := "JPH_" + recv + " *"
		if stripped != expectedPtr {
			continue
		}

		// Only emit methods if the receiver type has been defined somewhere.
		goRecv := recv // recv is already without JPH_ prefix
		if !alreadyEmitted[goRecv] {
			continue
		}

		// Receiver variable: first letter of the Go type, lowercased.
		recvVar := strings.ToLower(string(goRecv[0]))

		// Go method name: strip "Get" prefix if followed by uppercase letter.
		goMethod := method
		if strings.HasPrefix(method, "Get") && len(method) > 3 && method[3] >= 'A' && method[3] <= 'Z' {
			goMethod = method[3:]
		}

		// Build params and call args (skip first self param).
		var goParams []string
		var callArgs []string
		callArgs = append(callArgs, recvVar+".h")
		for _, p := range f.Params[1:] {
			paramName := safeParamName(p.Name)
			gt, callExpr := joltParamFromCType(p.CType, paramName)
			goParams = append(goParams, paramName+" "+gt)
			callArgs = append(callArgs, callExpr)
		}

		paramList := strings.Join(goParams, ", ")
		argList := strings.Join(callArgs, ", ")

		// Determine return type and body.
		ret := strings.TrimSpace(f.Return)
		goRet := strings.TrimPrefix(ret, "JPH_")

		if ret == "void" {
			// No return value.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) {\n", recvVar, goRecv, goMethod, paramList)
			fmt.Fprintf(&b, "    cjolt.%s(%s)\n", f.Name, argList)
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "}\n\n")
		} else if mathReturnTypes[goRet] {
			// Math type: use unsafe.Pointer cast.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    out := cjolt.%s(%s)\n", f.Name, argList)
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return *(*%s)(unsafe.Pointer(&out))\n", goRet)
			fmt.Fprintf(&b, "}\n\n")
		} else {
			// Scalar or other return: direct return.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    result := cjolt.%s(%s)\n", f.Name, argList)
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return result\n")
			fmt.Fprintf(&b, "}\n\n")
		}
	}
	return b.String()
}
