// skipMethods lists C method names that are handled by dedicated emitters and
// must not be turned into receiver methods.
var skipMethods = map[string]bool{
	"Create":   true,
	"Destroy":  true,
	"AddRef":   true,
	"Release":  true,
	"Init":     true,
	"SetProcs": true,
}

// emitPlainHandleTypes emits "type Foo struct{ h *cjolt.C_JPH_Foo }" for each
// opaque struct that doesn't have a Create/Destroy pair (Owned) and isn't
// in the RefCounted set.
func emitPlainHandleTypes(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, s := range h.Structs {
		if !s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		fmt.Fprintf(&b, "type %s struct{ h *cjolt.C_JPH_%s }\n\n", goName, goName)
	}
	return b.String()
}

// emitListenerTypes emits public Go API + NewX factory for each entry in
// Annotations.Listeners. Listener specs come from the global sidecar, not
// from the parsed header — the *Header parameter is unused by design but
// kept for emitter signature consistency.
func emitListenerTypes(_ *Header) string {
	var b strings.Builder
	for _, spec := range Annotations.Listeners {
		b.WriteString(emitOneListener(spec))
	}
	return b.String()
}

func emitOneListener(spec ListenerSpec) string {
	// Strip JPH_ prefix from CType to get Go type name.
	goName := strings.TrimPrefix(spec.CType, "JPH_") // ContactListener

	var b strings.Builder

	// 1. struct definition
	fmt.Fprintf(&b, "type %s struct {\n", goName)
	for _, m := range spec.Methods {
		sig := listenerMethodSignature(spec.CType, m)
		fmt.Fprintf(&b, "    %s %s\n", m.Name, sig)
	}
	b.WriteString("\n") // blank line for gofmt to separate alignment blocks
	fmt.Fprintf(&b, "    h      *cjolt.C_%s\n", spec.CType)
	b.WriteString("    handle cgo.Handle\n")
	b.WriteString("}\n\n")

	// 2. New<X> factory
	recv := receiverShortName(goName) // ContactListener -> cl
	fmt.Fprintf(&b, "func New%s(l %s) *%s {\n", goName, goName, goName)
	fmt.Fprintf(&b, "    %s := &l\n", recv)
	// Task 31: emit the bridge construction if this is a ContactListener.
	if spec.CType == "JPH_ContactListener" {
		b.WriteString(emitContactListenerBridge())
		fmt.Fprintf(&b, "    %s.handle = cgo.NewHandle(bridge)\n", recv)
	} else {
		fmt.Fprintf(&b, "    %s.handle = cgo.NewHandle(%s)\n", recv, recv)
	}
	fmt.Fprintf(&b, "    %s.h = cjolt.%s(unsafe.Pointer(uintptr(%s.handle)))\n",
		recv, listenerCreateFunc(spec), recv)
	fmt.Fprintf(&b, "    runtime.SetFinalizer(%s, (*%s).finalize)\n", recv, goName)
	fmt.Fprintf(&b, "    return %s\n}\n\n", recv)

	// 3. finalize method
	fmt.Fprintf(&b, "func (cl *%s) finalize() {\n", goName)
	fmt.Fprintf(&b, "    if cl.h != nil {\n")
	fmt.Fprintf(&b, "        cjolt.%s(cl.h)\n", listenerDestroyFunc(spec))
	fmt.Fprintf(&b, "        cl.h = nil\n")
	fmt.Fprintf(&b, "    }\n")
	fmt.Fprintf(&b, "    if cl.handle != 0 {\n")
	fmt.Fprintf(&b, "        cl.handle.Delete()\n")
	fmt.Fprintf(&b, "        cl.handle = 0\n")
	fmt.Fprintf(&b, "    }\n")
	fmt.Fprintf(&b, "}\n\n")

	return b.String()
}

// emitContactListenerBridge returns the bridge construction code for
// NewContactListener. The bridge is a *cjolt.ContactListenerHandle whose
// func fields are closures that convert C.* params to Go-native and call
// the user's func fields.
func emitContactListenerBridge() string {
	return `    bridge := &cjolt.ContactListenerHandle{
        OnContactValidate: func(b1, b2 *cjolt.C_JPH_Body, baseOffset *cjolt.C_JPH_RVec3, result *cjolt.C_JPH_CollideShapeResult) cjolt.C_JPH_ValidateResult {
            if cl.OnContactValidate != nil {
                return cjolt.C_JPH_ValidateResult(cl.OnContactValidate(
                    &Body{h: b1}, &Body{h: b2},
                    *(*RVec3)(unsafe.Pointer(baseOffset)),
                    (*CollideShapeResult)(unsafe.Pointer(result)),
                ))
            }
            return 0
        },
        OnContactAdded: func(b1, b2 *cjolt.C_JPH_Body, manifold *cjolt.C_JPH_ContactManifold, settings *cjolt.C_JPH_ContactSettings) {
            if cl.OnContactAdded != nil {
                cl.OnContactAdded(
                    &Body{h: b1}, &Body{h: b2},
                    (*ContactManifold)(unsafe.Pointer(manifold)),
                    (*ContactSettings)(unsafe.Pointer(settings)),
                )
            }
        },
        OnContactPersisted: func(b1, b2 *cjolt.C_JPH_Body, manifold *cjolt.C_JPH_ContactManifold, settings *cjolt.C_JPH_ContactSettings) {
            if cl.OnContactPersisted != nil {
                cl.OnContactPersisted(
                    &Body{h: b1}, &Body{h: b2},
                    (*ContactManifold)(unsafe.Pointer(manifold)),
                    (*ContactSettings)(unsafe.Pointer(settings)),
                )
            }
        },
        OnContactRemoved: func(subShapePair *cjolt.C_JPH_SubShapeIDPair) {
            if cl.OnContactRemoved != nil {
                cl.OnContactRemoved((*SubShapeIDPair)(unsafe.Pointer(subShapePair)))
            }
        },
    }
`
}

// listenerCreateFunc derives the cjolt _Create function name.
// JPH_ContactListener -> JPH_ContactListener_Create
func listenerCreateFunc(spec ListenerSpec) string {
	return spec.CType + "_Create"
}

// listenerDestroyFunc derives the cjolt _Destroy function name.
func listenerDestroyFunc(spec ListenerSpec) string {
	return spec.CType + "_Destroy"
}

// listenerMethodSignature returns the Go func signature for a listener
// callback. Hardcoded for known listener types because the param names and
// types aren't in the IR (they come from joltc's vtable typedefs which we
// don't parse).
func listenerMethodSignature(cType string, m ListenerMethod) string {
	if cType != "JPH_ContactListener" {
		// Future listeners — return placeholder; revisit when needed.
		return "func()"
	}
	switch m.Name {
	case "OnContactValidate":
		return "func(b1, b2 *Body, baseOffset RVec3, result *CollideShapeResult) ValidateResult"
	case "OnContactAdded":
		return "func(b1, b2 *Body, manifold *ContactManifold, settings *ContactSettings)"
	case "OnContactPersisted":
		return "func(b1, b2 *Body, manifold *ContactManifold, settings *ContactSettings)"
	case "OnContactRemoved":
		return "func(subShapePair *SubShapeIDPair)"
	}
	return "func()" // unknown method; placeholder
}

// receiverShortName produces a short Go receiver name from a CamelCase type by
// extracting and lowercasing each uppercase letter:
//
//	Body           → b
//	BodyInterface  → bi
//	PhysicsSystem  → ps
//	ContactListener → cl
func receiverShortName(goType string) string {
	var b strings.Builder
	for _, r := range goType {
		if r >= 'A' && r <= 'Z' {
			b.WriteRune(r + ('a' - 'A'))
		}
	}
	return b.String()
}

// abbreviateParamName shortens a param name to its first letter when the name
// is longer than 2 characters. Applied only in receiver methods (not constructors).
func abbreviateParamName(name string) string {
	if len(name) > 2 {
		return strings.ToLower(string([]rune(name)[0]))
	}
	return name
}

// methodParamFromCType maps a C type string to (goType, cjoltCallExpr, needsKeepAlive)
// for receiver method parameters. It extends joltParamFromCType with:
//   - Settings pointer params: const JPH_XSettings * → *XSettings + unsafe.Pointer cast
//   - Enum/typedef params: JPH_X (non-pointer, non-math) → X param type + C cast
func methodParamFromCType(cType, argName string) (goType, callExpr string, needsKeepAlive bool) {
	s := strings.TrimPrefix(cType, "const ")
	s = strings.TrimSpace(s)

	// Pointer type check.
	if base, ok := strings.CutSuffix(s, "*"); ok {
		base = strings.TrimSpace(base)
		// Settings pointer: const JPH_XSettings * → *XSettings
		stripped := strings.TrimPrefix(base, "JPH_")
		if strings.HasSuffix(stripped, "Settings") {
			goT := "*" + stripped
			cast := "(*cjolt.C_JPH_" + stripped + ")(unsafe.Pointer(" + argName + "))"
			return goT, cast, true
		}
		// Delegate to existing logic for other pointer types.
		gt, ce := joltParamFromCType(cType, argName)
		return gt, ce, false
	}

	// Non-pointer JPH_X type: treat as Go-side typedef/enum.
	if stripped, ok := strings.CutPrefix(s, "JPH_"); ok {
		cast := "cjolt.C_JPH_" + stripped + "(" + argName + ")"
		return stripped, cast, false
	}

	// Delegate to existing scalar logic.
	gt, ce := joltParamFromCType(cType, argName)
	return gt, ce, false
}

// parsePointerReturn checks if a C return type is JPH_X* (a plain opaque pointer)
// and returns (goTypeName, true) if so. Math/void returns give ("", false).
func parsePointerReturn(ret string) (goType string, ok bool) {
	ret = strings.TrimSpace(ret)
	if ret == "void" {
		return "", false
	}
	base, hasStar := strings.CutSuffix(ret, "*")
	if !hasStar {
		return "", false
	}
	base = strings.TrimSpace(base)
	goT := strings.TrimPrefix(base, "JPH_")
	// Math types are not returned as wrapped struct pointers from receiver methods.
	if mathReturnTypes[goT] {
		return "", false
	}
	return goT, true
}

// emitReceiverMethods walks Funcs and emits Go methods on receiver types for
// functions matching JPH_<Recv>_<Method> where the first param is the receiver.
func emitReceiverMethods(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if !ok {
			continue
		}
		if skipMethods[method] {
			continue
		}
		if len(f.Params) == 0 {
			continue
		}

		// Verify the first param is a receiver (self) for this type.
		// recv is already without JPH_ prefix (SplitMethod strips it).
		// C type looks like "JPH_Body *" or "const JPH_Body *".
		firstParam := f.Params[0]
		stripped := strings.TrimPrefix(firstParam.CType, "const ")
		stripped = strings.TrimSpace(stripped)
		// The C type retains the JPH_ prefix; recv does not.
		expectedPtr := "JPH_" + recv + " *"
		if stripped != expectedPtr {
			continue
		}

		// Only emit methods if the receiver type has been defined somewhere.
		goRecv := recv // recv is already without JPH_ prefix
		if !alreadyEmitted[goRecv] {
			continue
		}

		// Receiver variable: extract lowercase initials from each capital segment.
		recvVar := receiverShortName(goRecv)

		// Go method name: strip "Get" prefix if followed by uppercase letter.
		goMethod := method
		if strings.HasPrefix(method, "Get") && len(method) > 3 && method[3] >= 'A' && method[3] <= 'Z' {
			goMethod = method[3:]
		}

		// Build params and call args (skip first self param).
		var goParams []string
		var callArgs []string
		var settingsKeepAlives []string // param names needing KeepAlive after the cgo call
		callArgs = append(callArgs, recvVar+".h")
		for _, p := range f.Params[1:] {
			rawName := safeParamName(p.Name)
			// Abbreviate long param names in receiver methods only.
			paramName := abbreviateParamName(rawName)

			gt, callExpr, keepAlive := methodParamFromCType(p.CType, paramName)
			goParams = append(goParams, paramName+" "+gt)
			callArgs = append(callArgs, callExpr)
			if keepAlive {
				settingsKeepAlives = append(settingsKeepAlives, paramName)
			}
		}

		paramList := strings.Join(goParams, ", ")
		argList := strings.Join(callArgs, ", ")

		// Determine return type and body.
		ret := strings.TrimSpace(f.Return)

		// Check for pointer return: JPH_X* → *X (plain opaque type).
		if ptrGoType, isPtrReturn := parsePointerReturn(ret); isPtrReturn {
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) *%s {\n", recvVar, goRecv, goMethod, paramList, ptrGoType)
			fmt.Fprintf(&b, "    out := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return &%s{h: out}\n", ptrGoType)
			fmt.Fprintf(&b, "}\n\n")
			continue
		}

		goRet := strings.TrimPrefix(ret, "JPH_")

		if ret == "void" {
			// No return value.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) {\n", recvVar, goRecv, goMethod, paramList)
			fmt.Fprintf(&b, "    cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "}\n\n")
		} else if mathReturnTypes[goRet] {
			// Math type: use unsafe.Pointer cast.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    out := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return *(*%s)(unsafe.Pointer(&out))\n", goRet)
			fmt.Fprintf(&b, "}\n\n")
		} else {
			// Scalar or other return: direct return.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    result := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return result\n")
			fmt.Fprintf(&b, "}\n\n")
		}
	}
	return b.String()
}
