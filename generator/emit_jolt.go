// EmitJolt returns the source for jolt/jolt_generated.go.
func EmitJolt(h *Header) string {
	var b strings.Builder
	b.WriteString("// Code generated by jolt-go generator. DO NOT EDIT.\n\npackage jolt\n\n")
	b.WriteString(`import (
    "runtime"
    "runtime/cgo"
    "unsafe"

    "github.com/gataengine/jolt-go/internal/cjolt"
)

// silence unused-import warnings until first use
var _ = unsafe.Sizeof(0)
var _ = runtime.GC
var _ cgo.Handle

`)

	// Track which Go types have already been emitted as struct definitions.
	alreadyEmitted := map[string]bool{}

	// Math types are defined in math.go, not generated. Pre-mark them so emitters
	// don't re-emit them or their methods.
	for t := range mathReturnTypes {
		alreadyEmitted[t] = true
	}

	// Build the complete set of Go types that have a .h handle field and set
	// the package-level variable used by param-type resolution.
	joltHandleTypes = buildKnownHandleTypes(h)

	// Emit Go-side aliases for integer typedefs (e.g. ObjectLayer = uint16).
	b.WriteString(emitTypedefs(h))

	// Build a set of listener Go type names so we can skip them in emitOwned
	// and emitPlainHandleTypes (listeners get their own dedicated emitter).
	listenerTypes := make(map[string]bool)
	for _, spec := range Annotations.Listeners {
		goName := strings.TrimPrefix(spec.CType, "JPH_")
		listenerTypes[goName] = true
		// Pre-mark as emitted so plain handle emitter skips them.
		alreadyEmitted[goName] = true
	}

	// Pair Create/Destroy by type name and emit one OwnedType block per pair
	// that is *not* in the RefCounted set and not a listener (listeners get their own emitter).
	pairs := pairCreateDestroy(h)
	for _, p := range pairs {
		if isRefCounted(p.GoType) {
			continue
		}
		if listenerTypes[p.GoType] {
			continue
		}
		b.WriteString(emitOwned(p))
		alreadyEmitted[p.GoType] = true
	}

	// Emit ref-counted type definitions and constructors.
	b.WriteString(emitRefCountedTypes(h))
	for _, name := range Annotations.RefCounted {
		alreadyEmitted[name] = true
	}

	// Emit plain handle wrappers for opaque structs not covered above.
	b.WriteString(emitPlainHandleTypes(h, alreadyEmitted))
	// Update alreadyEmitted with any new types from plain handle pass.
	for _, s := range h.Structs {
		if s.Opaque {
			goName := strings.TrimPrefix(s.Name, "JPH_")
			alreadyEmitted[goName] = true
		}
	}

	// Emit settings structs (Approach 1: layout-match Go struct + SetX setters).
	for _, s := range h.Structs {
		if s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if _, ok := Annotations.SettingsInit[goName]; !ok {
			continue
		}
		b.WriteString(emitSettingsType(s))
		alreadyEmitted[goName] = true
	}

	// Emit concrete (non-opaque) structs not covered above as opaque Go types.
	// These allow unsafe.Pointer casts from the cjolt layer (e.g. ContactSettings,
	// SubShapeIDPair) without exposing their C layout in Go.
	b.WriteString(emitConcreteStructTypes(h, alreadyEmitted))
	// Update alreadyEmitted for concrete structs.
	for _, s := range h.Structs {
		if !s.Opaque {
			goName := strings.TrimPrefix(s.Name, "JPH_")
			alreadyEmitted[goName] = true
		}
	}

	// Emit enum type aliases (e.g. ValidateResult = C.JPH_ValidateResult).
	b.WriteString(emitEnumAliases(h, alreadyEmitted))

	// Emit function-pointer typedef aliases.
	b.WriteString(emitFuncTypedefAliases(h, alreadyEmitted))

	// Emit listener types (struct-of-funcs + NewX factory + finalize).
	b.WriteString(emitListenerTypes(h))

	// Emit method bindings on receiver types.
	b.WriteString(emitReceiverMethods(h, alreadyEmitted))

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return b.String()
	}
	return string(out)
}

// ownedPair pairs a Create function with its matching Destroy function for an owned (non-ref-counted) type.
type ownedPair struct {
	GoType  string
	Create  Func
	Destroy Func
}

// pairCreateDestroy returns matched (Create, Destroy) function pairs from the header.
func pairCreateDestroy(h *Header) []ownedPair {
	creates := map[string]Func{}
	destroys := map[string]Func{}
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if !ok {
			continue
		}
		switch method {
		case "Create":
			creates[recv] = f
		case "Destroy":
			destroys[recv] = f
		}
	}
	var out []ownedPair
	for t, c := range creates {
		if d, ok := destroys[t]; ok {
			out = append(out, ownedPair{GoType: t, Create: c, Destroy: d})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].GoType < out[j].GoType })
	return out
}

// isRefCounted reports whether a type is in the RefCounted sidecar list.
func isRefCounted(t string) bool {
	return slices.Contains(Annotations.RefCounted, t)
}

// emitRefCountedTypes emits struct definitions for all RefCounted types
// (using Annotations.Inheritance for parents) and constructors with
// finalizer-registered Release for types that have a JPH_X_Create function.
func emitRefCountedTypes(h *Header) string {
	var b strings.Builder

	// 1. Type definitions for every RefCounted type.
	for _, name := range Annotations.RefCounted {
		if parent, ok := Annotations.Inheritance[name]; ok {
			// Embedded inheritance.
			fmt.Fprintf(&b, "type %s struct{ %s }\n", name, parent)
		} else {
			// Root of hierarchy (Shape, PhysicsMaterial) — holds the cjolt handle.
			fmt.Fprintf(&b, "type %s struct{ h *cjolt.C_JPH_%s }\n", name, name)
		}
	}
	b.WriteString("\n")

	// 2. Constructors for types that have a JPH_X_Create function.
	creates := map[string]Func{}
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if ok && method == "Create" && isRefCounted(recv) {
			creates[recv] = f
		}
	}
	// Emit in stable order: iterate Annotations.RefCounted to preserve declaration order.
	for _, goType := range Annotations.RefCounted {
		f, ok := creates[goType]
		if !ok {
			continue
		}
		b.WriteString(emitRefCountedConstructor(goType, f))
	}
	return b.String()
}

// emitRefCountedConstructor emits the public constructor and hidden finalizer
// for a single ref-counted type.
func emitRefCountedConstructor(goType string, f Func) string {
	var b strings.Builder

	// Build Go param signature and cjolt call arguments.
	var goParams []string
	var cjoltArgs []string
	for _, p := range f.Params {
		goName := safeParamName(p.Name)
		gt, callExpr := joltParamFromCType(p.CType, goName)
		goParams = append(goParams, goName+" "+gt)
		cjoltArgs = append(cjoltArgs, callExpr)
	}

	paramList := strings.Join(goParams, ", ")
	argList := strings.Join(cjoltArgs, ", ")

	// Find the root ref-counted type to know what handle type Shape.h has.
	root := rootRefCountedType(goType)

	fmt.Fprintf(&b, "func New%s(%s) *%s {\n", goType, paramList, goType)
	fmt.Fprintf(&b, "    raw := cjolt.%s(%s)\n", f.Name, argList)
	// Cast the returned *C.JPH_<GoType> to the root handle type *C.JPH_<Root>.
	// The C inheritance means the pointer values are layout-compatible.
	if root != goType {
		fmt.Fprintf(&b, "    h := (*cjolt.C_JPH_%s)(unsafe.Pointer(raw))\n", root)
	} else {
		fmt.Fprintf(&b, "    h := raw\n")
	}
	chain := buildEmbeddedChain(goType)
	fmt.Fprintf(&b, "    s := &%s{%s}\n", goType, chain)
	fmt.Fprintf(&b, "    runtime.SetFinalizer(s, (*%s).finalize)\n", goType)
	fmt.Fprintf(&b, "    return s\n}\n\n")

	// finalize method — calls the root type's Destroy to free the underlying C object.
	fmt.Fprintf(&b, "func (s *%s) finalize() {\n", goType)
	fmt.Fprintf(&b, "    if s.h != nil {\n")
	fmt.Fprintf(&b, "        cjolt.JPH_%s_Destroy(s.h)\n", root)
	fmt.Fprintf(&b, "        s.h = nil\n")
	fmt.Fprintf(&b, "    }\n}\n\n")

	return b.String()
}

// joltParamFromCType maps a C type string to (goType, cjoltCallExpr) for use in
// the public jolt API.
func joltParamFromCType(cType, argName string) (goType, callExpr string) {
	s := strings.TrimPrefix(cType, "const ")
	s = strings.TrimSpace(s)
	// Pointer-to-pointer (T **): expose as unsafe.Pointer in the jolt API.
	if _, ok := strings.CutSuffix(s, " **"); ok {
		return "unsafe.Pointer", argName
	}
	// Pointer type: strip trailing '*'.
	if base, ok := strings.CutSuffix(s, "*"); ok {
		base = strings.TrimSpace(base)
		// Strip const qualifier from the base type (handles "const const T *" → "T *").
		base = strings.TrimPrefix(base, "const ")
		base = strings.TrimSpace(base)
		// void*, char* and primitive pointer types → unsafe.Pointer.
		switch base {
		case "void", "char", "float", "double",
			"uint8_t", "uint16_t", "uint32_t", "uint64_t",
			"int8_t", "int16_t", "int32_t", "int64_t", "bool", "_Bool":
			return "unsafe.Pointer", argName
		}
		switch base {
		case "JPH_Vec3":
			return "Vec3", "(*cjolt.C_JPH_Vec3)(unsafe.Pointer(&" + argName + "))"
		case "JPH_Quat":
			return "Quat", "(*cjolt.C_JPH_Quat)(unsafe.Pointer(&" + argName + "))"
		case "JPH_RVec3":
			return "RVec3", "(*cjolt.C_JPH_RVec3)(unsafe.Pointer(&" + argName + "))"
		}
		goTypeName := strings.TrimPrefix(base, "JPH_")
		// Only use .h accessor if the Go type is a known opaque handle wrapper.
		// Concrete value types (JPH_Plane, JPH_AABox, etc.) don't have .h.
		if joltHandleTypes[goTypeName] {
			return "*" + goTypeName, argName + ".h"
		}
		// Concrete JPH_ value type: accept as unsafe.Pointer but cast to the
		// cjolt C type at the call site so cgo's type checking passes.
		cast := "(*cjolt.C_" + base + ")(unsafe.Pointer(" + argName + "))"
		return "unsafe.Pointer", cast
	}
	// Scalars — map to Go-native; no cast needed (cjolt wrapper already accepts Go-native).
	switch s {
	case "float":
		return "float32", argName
	case "double":
		return "float64", argName
	case "bool", "_Bool":
		return "bool", argName
	case "int", "int32_t":
		return "int32", argName
	case "unsigned int", "uint32_t":
		return "uint32", argName
	case "uint8_t":
		return "uint8", argName
	case "int8_t":
		return "int8", argName
	case "uint16_t":
		return "uint16", argName
	case "int16_t":
		return "int16", argName
	case "uint64_t":
		return "uint64", argName
	case "int64_t":
		return "int64", argName
	}
	// Unknown: pass through (will fail to compile for exotic types — Task 33).
	return s, argName
}

// rootRefCountedType walks up Annotations.Inheritance from goType to find
// the topmost ancestor (the type that holds the actual cjolt handle).
// For a root type with no parent, returns goType unchanged.
func rootRefCountedType(goType string) string {
	cur := goType
	for {
		parent, ok := Annotations.Inheritance[cur]
		if !ok {
			return cur
		}
		cur = parent
	}
}

// buildEmbeddedChain produces the struct literal initialiser for a ref-counted
// type with embedded parents, e.g.:
//
//	BoxShape    → "ConvexShape: ConvexShape{Shape: Shape{h: h}}"
//	ConvexShape → "Shape: Shape{h: h}"
//	Shape       → "h: h"
func buildEmbeddedChain(goType string) string {
	parent, ok := Annotations.Inheritance[goType]
	if !ok {
		// Root type: just the handle field.
		return "h: h"
	}
	return parent + ": " + parent + "{" + buildEmbeddedChain(parent) + "}"
}

// emitOwned emits the public Go API for one owned-type pair: type, constructor with finalizer, Close, finalize.
func emitOwned(p ownedPair) string {
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n    h *cjolt.C_JPH_%s\n}\n\n", p.GoType, p.GoType)

	// Build constructor signature from the Create function's params.
	var goParams []string
	var callArgs []string
	for _, param := range p.Create.Params {
		safe := safeParamName(param.Name)
		gt, ce := joltParamFromCType(param.CType, safe)
		goParams = append(goParams, safe+" "+gt)
		callArgs = append(callArgs, ce)
	}
	paramList := strings.Join(goParams, ", ")
	argList := strings.Join(callArgs, ", ")

	fmt.Fprintf(&b, "func New%s(%s) *%s {\n", p.GoType, paramList, p.GoType)
	fmt.Fprintf(&b, "    p := &%s{h: cjolt.%s(%s)}\n", p.GoType, p.Create.Name, argList)
	fmt.Fprintf(&b, "    runtime.SetFinalizer(p, (*%s).finalize)\n", p.GoType)
	fmt.Fprintf(&b, "    return p\n}\n\n")

	fmt.Fprintf(&b, `func (p *%[1]s) Close() error {
    if p.h != nil {
        cjolt.JPH_%[1]s_Destroy(p.h)
        p.h = nil
        runtime.SetFinalizer(p, nil)
    }
    return nil
}

func (p *%[1]s) finalize() { _ = p.Close() }

`, p.GoType)
	return b.String()
}

// emitTypedefs emits Go-side aliases for joltc integer typedefs.
// e.g., "typedef uint16_t JPH_ObjectLayer" → "type ObjectLayer = uint16"
func emitTypedefs(h *Header) string {
	var b strings.Builder
	cToGo := map[string]string{
		"uint8_t":  "uint8",
		"int8_t":   "int8",
		"uint16_t": "uint16",
		"int16_t":  "int16",
		"uint32_t": "uint32",
		"int32_t":  "int32",
		"uint64_t": "uint64",
		"int64_t":  "int64",
		"float":    "float32",
		"double":   "float64",
	}
	// Sort for deterministic output.
	var aliases []string
	for k := range h.Typedefs {
		aliases = append(aliases, k)
	}
	sort.Strings(aliases)

	for _, alias := range aliases {
		underlying := h.Typedefs[alias]
		goType, ok := cToGo[underlying]
		if !ok {
			continue
		}
		goName := strings.TrimPrefix(alias, "JPH_")
		fmt.Fprintf(&b, "type %s = %s\n", goName, goType)
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

// emitSettingsType emits a Go struct mirroring a JPH_*Settings C struct (Approach 1).
// Every scalar/math field maps directly. Pointer fields become unexported uintptr
// slots with a SetX(*X) setter that stores via unsafe.Pointer + KeepAlive.
func emitSettingsType(s Struct) string {
	goName := strings.TrimPrefix(s.Name, "JPH_")
	var b strings.Builder
	fmt.Fprintf(&b, "type %s struct {\n", goName)

	type ptrSetter struct {
		Field string // "Shape"
		Type  string // "Shape" (without JPH_)
	}
	var pointerFields []ptrSetter

	for _, f := range s.Fields {
		cType := f.CType
		// Pointer fields become unexported uintptr slots and need setters.
		if strings.HasSuffix(cType, "*") {
			// e.g., "JPH_Shape *" → field "shape uintptr"
			pointerFields = append(pointerFields, ptrSetter{
				Field: f.Name,
				Type:  strings.TrimSpace(strings.TrimPrefix(strings.TrimSuffix(strings.TrimSpace(cType), "*"), "JPH_")),
			})
			// Lowercase first letter for the unexported slot.
			slotName := strings.ToLower(f.Name[:1]) + f.Name[1:]
			fmt.Fprintf(&b, "    %s uintptr\n", slotName)
			continue
		}
		// Map C type to Go type.
		goType := mapCFieldTypeToGo(cType)
		fmt.Fprintf(&b, "    %s %s\n", f.Name, goType)
	}
	b.WriteString("}\n\n")

	for _, p := range pointerFields {
		slotName := strings.ToLower(p.Field[:1]) + p.Field[1:]
		argName := strings.ToLower(p.Type[:1]) + p.Type[1:]
		fmt.Fprintf(&b, "func (s *%s) Set%s(%s *%s) {\n", goName, p.Field, argName, p.Type)
		fmt.Fprintf(&b, "    s.%s = uintptr(unsafe.Pointer(%s.h))\n", slotName, argName)
		fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", argName)
		b.WriteString("}\n\n")
	}
	return b.String()
}

// emitFuncTypedefAliases emits Go type aliases for function-pointer typedef types.
// e.g. JPH_TireMaxImpulseCallback → type TireMaxImpulseCallback = cjolt.C_JPH_TireMaxImpulseCallback
func emitFuncTypedefAliases(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, ft := range h.FuncTypedefs {
		goName := strings.TrimPrefix(ft, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		fmt.Fprintf(&b, "type %s = cjolt.C_%s\n", goName, ft)
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

// emitConcreteStructTypes emits Go type aliases for non-opaque (concrete) JPH_ structs
// that aren't already emitted via SettingsInit or math.go. These types appear in
// listener bridge code and receiver methods and need Go-accessible type names.
func emitConcreteStructTypes(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, s := range h.Structs {
		if s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		// Skip math types defined in math.go.
		if mathReturnTypes[goName] {
			continue
		}
		// Emit as a Go type alias to the cjolt-exposed C type.
		fmt.Fprintf(&b, "type %s = cjolt.C_%s\n", goName, s.Name)
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

// emitEnumAliases emits Go type aliases for enums defined in joltc.h.
// Enums are exposed as C types in cjolt; here we alias them in jolt for usability.
func emitEnumAliases(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, e := range h.Enums {
		goName := strings.TrimPrefix(e.Name, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		// Emit as a Go type alias to the cjolt-exposed C type.
		fmt.Fprintf(&b, "type %s = cjolt.C_%s\n", goName, e.Name)
	}
	if b.Len() > 0 {
		b.WriteString("\n")
	}
	return b.String()
}

// mapCFieldTypeToGo maps a C field type string to the corresponding Go type.
// JPH_Vec3 → Vec3, JPH_ObjectLayer → ObjectLayer (typedef alias),
// uint64_t → uint64, _Bool → bool, float → float32, etc.
func mapCFieldTypeToGo(cType string) string {
	cType = strings.TrimSpace(cType)
	// JPH_-prefixed types: strip the prefix; the type is defined either in math.go
	// (Vec3/Quat/...) or via emitTypedefs (ObjectLayer/MotionType) or as opaque struct.
	if rest, ok := strings.CutPrefix(cType, "JPH_"); ok {
		return rest
	}
	// C scalars.
	cToGo := map[string]string{
		"uint8_t":  "uint8",
		"int8_t":   "int8",
		"uint16_t": "uint16",
		"int16_t":  "int16",
		"uint32_t": "uint32",
		"int32_t":  "int32",
		"uint64_t": "uint64",
		"int64_t":  "int64",
		"float":    "float32",
		"double":   "float64",
		"bool":     "bool",
		"_Bool":    "bool",
	}
	if goT, ok := cToGo[cType]; ok {
		return goT
	}
	// Unknown type: pass through (likely fails compile in Task 33).
	return cType
}

// mathReturnTypes is the set of Go math types that require the unsafe.Pointer
// cast pattern when returned from cjolt functions. Also used to skip method
// generation for types already hand-written in math.go.
var mathReturnTypes = map[string]bool{
	"Vec3": true, "Quat": true, "Mat44": true,
	"RVec3": true, "RMat4": true,
}

// joltHandleTypes is the set of Go type names that have a .h handle field
// (opaque handle wrappers, ref-counted types, listener types, owned types).
// Set by EmitJolt before any emitter runs.
var joltHandleTypes map[string]bool

// buildKnownHandleTypes builds the complete set of Go type names that will have
// a .h field in the generated code. Used by joltParamFromCType to distinguish
// opaque handle types (argName.h) from concrete value types (unsafe.Pointer).
func buildKnownHandleTypes(h *Header) map[string]bool {
	known := make(map[string]bool)
	// All opaque structs become handle types.
	for _, s := range h.Structs {
		if s.Opaque {
			known[strings.TrimPrefix(s.Name, "JPH_")] = true
		}
	}
	// All ref-counted types have a .h field (directly or via embedded root).
	for _, name := range Annotations.RefCounted {
		known[name] = true
	}
	// All listener types have a .h field.
	for _, spec := range Annotations.Listeners {
		known[strings.TrimPrefix(spec.CType, "JPH_")] = true
	}
	// Math types (Vec3, Quat, etc.) are NOT handle types — handled specially.
	return known
}

// skipMethods lists C method names that are handled by dedicated emitters and
// must not be turned into receiver methods.
var skipMethods = map[string]bool{
	"Create":   true,
	"Destroy":  true,
	"AddRef":   true,
	"Release":  true,
	"Init":     true,
	"SetProcs": true,
}

// skipFunctions lists full C function names whose generated Go receiver methods
// are replaced by hand-written carve-outs in jolt_handwritten.go.
// The carve-out may have the same Go name but adds nil-safety or a different
// return type that the generator cannot produce.
var skipFunctions = map[string]bool{
	"JPH_Shape_CollidePoint": true, // carve-out handles nil shapeFilter
}

// emitPlainHandleTypes emits "type Foo struct{ h *cjolt.C_JPH_Foo }" for each
// opaque struct that doesn't have a Create/Destroy pair (Owned) and isn't
// in the RefCounted set.
func emitPlainHandleTypes(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, s := range h.Structs {
		if !s.Opaque {
			continue
		}
		goName := strings.TrimPrefix(s.Name, "JPH_")
		if alreadyEmitted[goName] {
			continue
		}
		fmt.Fprintf(&b, "type %s struct{ h *cjolt.C_JPH_%s }\n\n", goName, goName)
	}
	return b.String()
}

// emitListenerTypes emits public Go API + NewX factory for each entry in
// Annotations.Listeners. Listener specs come from the global sidecar, not
// from the parsed header — the *Header parameter is unused by design but
// kept for emitter signature consistency.
func emitListenerTypes(_ *Header) string {
	var b strings.Builder
	for _, spec := range Annotations.Listeners {
		b.WriteString(emitOneListener(spec))
	}
	return b.String()
}

func emitOneListener(spec ListenerSpec) string {
	// Strip JPH_ prefix from CType to get Go type name.
	goName := strings.TrimPrefix(spec.CType, "JPH_") // ContactListener

	var b strings.Builder

	// 1. struct definition
	fmt.Fprintf(&b, "type %s struct {\n", goName)
	for _, m := range spec.Methods {
		sig := listenerMethodSignature(spec.CType, m)
		fmt.Fprintf(&b, "    %s %s\n", m.Name, sig)
	}
	b.WriteString("\n") // blank line for gofmt to separate alignment blocks
	fmt.Fprintf(&b, "    h      *cjolt.C_%s\n", spec.CType)
	b.WriteString("    handle cgo.Handle\n")
	b.WriteString("}\n\n")

	// 2. New<X> factory
	recv := receiverShortName(goName) // ContactListener -> cl
	fmt.Fprintf(&b, "func New%s(l %s) *%s {\n", goName, goName, goName)
	fmt.Fprintf(&b, "    %s := &l\n", recv)
	// Task 31: emit the bridge construction if this is a ContactListener.
	if spec.CType == "JPH_ContactListener" {
		b.WriteString(emitContactListenerBridge())
		fmt.Fprintf(&b, "    %s.handle = cgo.NewHandle(bridge)\n", recv)
	} else {
		fmt.Fprintf(&b, "    %s.handle = cgo.NewHandle(%s)\n", recv, recv)
	}
	fmt.Fprintf(&b, "    %s.h = cjolt.%s(*(*unsafe.Pointer)(unsafe.Pointer(&%s.handle)))\n",
		recv, listenerCreateFunc(spec), recv)
	fmt.Fprintf(&b, "    runtime.SetFinalizer(%s, (*%s).finalize)\n", recv, goName)
	fmt.Fprintf(&b, "    return %s\n}\n\n", recv)

	// 3. finalize method
	fmt.Fprintf(&b, "func (cl *%s) finalize() {\n", goName)
	fmt.Fprintf(&b, "    if cl.h != nil {\n")
	fmt.Fprintf(&b, "        cjolt.%s(cl.h)\n", listenerDestroyFunc(spec))
	fmt.Fprintf(&b, "        cl.h = nil\n")
	fmt.Fprintf(&b, "    }\n")
	fmt.Fprintf(&b, "    if cl.handle != 0 {\n")
	fmt.Fprintf(&b, "        cl.handle.Delete()\n")
	fmt.Fprintf(&b, "        cl.handle = 0\n")
	fmt.Fprintf(&b, "    }\n")
	fmt.Fprintf(&b, "}\n\n")

	return b.String()
}

// emitContactListenerBridge returns the bridge construction code for
// NewContactListener. The bridge is a *cjolt.ContactListenerHandle whose
// func fields are closures that convert C.* params to Go-native and call
// the user's func fields.
func emitContactListenerBridge() string {
	return `    bridge := &cjolt.ContactListenerHandle{
        OnContactValidate: func(b1, b2 *cjolt.C_JPH_Body, baseOffset *cjolt.C_JPH_RVec3, result *cjolt.C_JPH_CollideShapeResult) cjolt.C_JPH_ValidateResult {
            if cl.OnContactValidate != nil {
                return cjolt.C_JPH_ValidateResult(cl.OnContactValidate(
                    &Body{h: b1}, &Body{h: b2},
                    *(*RVec3)(unsafe.Pointer(baseOffset)),
                    (*CollideShapeResult)(unsafe.Pointer(result)),
                ))
            }
            return 0
        },
        OnContactAdded: func(b1, b2 *cjolt.C_JPH_Body, manifold *cjolt.C_JPH_ContactManifold, settings *cjolt.C_JPH_ContactSettings) {
            if cl.OnContactAdded != nil {
                cl.OnContactAdded(
                    &Body{h: b1}, &Body{h: b2},
                    (*ContactManifold)(unsafe.Pointer(manifold)),
                    (*ContactSettings)(unsafe.Pointer(settings)),
                )
            }
        },
        OnContactPersisted: func(b1, b2 *cjolt.C_JPH_Body, manifold *cjolt.C_JPH_ContactManifold, settings *cjolt.C_JPH_ContactSettings) {
            if cl.OnContactPersisted != nil {
                cl.OnContactPersisted(
                    &Body{h: b1}, &Body{h: b2},
                    (*ContactManifold)(unsafe.Pointer(manifold)),
                    (*ContactSettings)(unsafe.Pointer(settings)),
                )
            }
        },
        OnContactRemoved: func(subShapePair *cjolt.C_JPH_SubShapeIDPair) {
            if cl.OnContactRemoved != nil {
                cl.OnContactRemoved((*SubShapeIDPair)(unsafe.Pointer(subShapePair)))
            }
        },
    }
`
}

// listenerCreateFunc derives the cjolt _Create function name.
// JPH_ContactListener -> JPH_ContactListener_Create
func listenerCreateFunc(spec ListenerSpec) string {
	return spec.CType + "_Create"
}

// listenerDestroyFunc derives the cjolt _Destroy function name.
func listenerDestroyFunc(spec ListenerSpec) string {
	return spec.CType + "_Destroy"
}

// listenerMethodSignature returns the Go func signature for a listener
// callback. Hardcoded for known listener types because the param names and
// types aren't in the IR (they come from joltc's vtable typedefs which we
// don't parse).
func listenerMethodSignature(cType string, m ListenerMethod) string {
	if cType != "JPH_ContactListener" {
		// Future listeners — return placeholder; revisit when needed.
		return "func()"
	}
	switch m.Name {
	case "OnContactValidate":
		return "func(b1, b2 *Body, baseOffset RVec3, result *CollideShapeResult) ValidateResult"
	case "OnContactAdded":
		return "func(b1, b2 *Body, manifold *ContactManifold, settings *ContactSettings)"
	case "OnContactPersisted":
		return "func(b1, b2 *Body, manifold *ContactManifold, settings *ContactSettings)"
	case "OnContactRemoved":
		return "func(subShapePair *SubShapeIDPair)"
	}
	return "func()" // unknown method; placeholder
}

// receiverShortName produces a short Go receiver name from a CamelCase type by
// extracting and lowercasing each uppercase letter:
//
//	Body           → b
//	BodyInterface  → bi
//	PhysicsSystem  → ps
//	ContactListener → cl
func receiverShortName(goType string) string {
	var b strings.Builder
	for _, r := range goType {
		if r >= 'A' && r <= 'Z' {
			b.WriteRune(r + ('a' - 'A'))
		}
	}
	return b.String()
}

// abbreviateParamName shortens a param name to its first letter when the name
// is longer than 2 characters. Applied only in receiver methods (not constructors).
func abbreviateParamName(name string) string {
	if len(name) > 2 {
		return strings.ToLower(string([]rune(name)[0]))
	}
	return name
}

// methodParamFromCType maps a C type string to (goType, cjoltCallExpr, needsKeepAlive)
// for receiver method parameters. It extends joltParamFromCType with:
//   - Settings pointer params: const JPH_XSettings * → *XSettings + unsafe.Pointer cast
//   - Enum/typedef params: JPH_X (non-pointer, non-math) → X param type + C cast
func methodParamFromCType(cType, argName string) (goType, callExpr string, needsKeepAlive bool) {
	s := strings.TrimPrefix(cType, "const ")
	s = strings.TrimSpace(s)

	// Pointer-to-pointer (T **): expose as unsafe.Pointer.
	if _, ok := strings.CutSuffix(s, " **"); ok {
		return "unsafe.Pointer", argName, false
	}
	// Pointer type check.
	if base, ok := strings.CutSuffix(s, "*"); ok {
		base = strings.TrimSpace(base)
		// Strip const qualifier (handles "const const T *" → "T").
		base = strings.TrimPrefix(base, "const ")
		base = strings.TrimSpace(base)
		// Settings pointer: const JPH_XSettings * → *XSettings
		stripped := strings.TrimPrefix(base, "JPH_")
		if strings.HasSuffix(stripped, "Settings") {
			goT := "*" + stripped
			// If this Settings type is an opaque handle wrapper (has a .h field),
			// use argName.h so cgo receives the underlying *C.JPH_XSettings pointer.
			// Otherwise (concrete layout-mirror struct) cast via unsafe.Pointer.
			if joltHandleTypes[stripped] {
				return goT, argName + ".h", true
			}
			cast := "(*cjolt.C_JPH_" + stripped + ")(unsafe.Pointer(" + argName + "))"
			return goT, cast, true
		}
		// Delegate to existing logic for other pointer types.
		gt, ce := joltParamFromCType(cType, argName)
		return gt, ce, false
	}

	// Non-pointer JPH_X type: treat as Go-side typedef/enum.
	if stripped, ok := strings.CutPrefix(s, "JPH_"); ok {
		// Apply special name mappings (C name → Go name) for types with
		// different naming between joltc.h and math.go.
		switch stripped {
		case "RMat4":
			// math.go defines RMat44 (struct); pass via unsafe.Pointer reinterpret.
			cast := "*(*cjolt.C_JPH_RMat4)(unsafe.Pointer(&" + argName + "))"
			return "RMat44", cast, false
		case "Mat4":
			// Analogous to RMat4.
			cast := "*(*cjolt.C_JPH_Mat4)(unsafe.Pointer(&" + argName + "))"
			return "Mat44", cast, false
		}
		cast := "cjolt.C_JPH_" + stripped + "(" + argName + ")"
		return stripped, cast, false
	}

	// Delegate to existing scalar logic.
	gt, ce := joltParamFromCType(cType, argName)
	return gt, ce, false
}

// parsePointerReturn checks if a C return type is JPH_X* (a plain opaque pointer)
// and returns (goTypeName, true) if so. Math/void/char/primitive returns give ("", false).
func parsePointerReturn(ret string) (goType string, ok bool) {
	ret = strings.TrimSpace(ret)
	if ret == "void" {
		return "", false
	}
	// Strip outer const qualifier.
	ret = strings.TrimPrefix(ret, "const ")
	ret = strings.TrimSpace(ret)
	// Pointer-to-pointer (T **) → not a typed return for the jolt API.
	if strings.HasSuffix(ret, " **") {
		return "", false
	}
	base, hasStar := strings.CutSuffix(ret, "*")
	if !hasStar {
		return "", false
	}
	base = strings.TrimSpace(base)
	// Strip any nested const from base.
	base = strings.TrimPrefix(base, "const ")
	base = strings.TrimSpace(base)
	// void *, char *, or primitive pointer → not a typed opaque pointer return.
	switch base {
	case "void", "char", "float", "double", "int", "uint8_t", "uint16_t", "uint32_t", "uint64_t",
		"int8_t", "int16_t", "int32_t", "int64_t", "bool", "_Bool":
		return "", false
	}
	goT := strings.TrimPrefix(base, "JPH_")
	// Math types are not returned as wrapped struct pointers from receiver methods.
	if mathReturnTypes[goT] {
		return "", false
	}
	// Non-handle types (scalar typedefs like BodyID, enums, etc.) are not wrapped in structs.
	// Only opaque handle wrapper types have a .h field and can be returned as *T.
	if !joltHandleTypes[goT] {
		return "", false
	}
	return goT, true
}

// emitReceiverMethods walks Funcs and emits Go methods on receiver types for
// functions matching JPH_<Recv>_<Method> where the first param is the receiver.
func emitReceiverMethods(h *Header, alreadyEmitted map[string]bool) string {
	var b strings.Builder
	for _, f := range h.Funcs {
		recv, method, ok := SplitMethod(f.Name)
		if !ok {
			continue
		}
		if skipMethods[method] {
			continue
		}
		if skipFunctions[f.Name] {
			continue
		}
		if len(f.Params) == 0 {
			continue
		}

		// Verify the first param is a receiver (self) for this type.
		// recv is already without JPH_ prefix (SplitMethod strips it).
		// C type looks like "JPH_Body *" or "const JPH_Body *".
		firstParam := f.Params[0]
		stripped := strings.TrimPrefix(firstParam.CType, "const ")
		stripped = strings.TrimSpace(stripped)
		// The C type retains the JPH_ prefix; recv does not.
		expectedPtr := "JPH_" + recv + " *"
		if stripped != expectedPtr {
			continue
		}

		// Only emit methods if the receiver type has been defined somewhere.
		goRecv := recv // recv is already without JPH_ prefix
		if !alreadyEmitted[goRecv] {
			continue
		}
		// Skip methods for math types (Vec3, Quat, etc.) — hand-written in math.go.
		if mathReturnTypes[goRecv] {
			continue
		}
		// Skip methods for concrete value types (type aliases to cjolt C_ types).
		// These types don't have a .h handle field; they are the C struct directly.
		// Methods on these types would fail because: (1) they're type aliases so Go
		// forbids new methods, and (2) .h is not a valid field on value types.
		if !joltHandleTypes[goRecv] {
			continue
		}

		// Receiver variable: extract lowercase initials from each capital segment.
		recvVar := receiverShortName(goRecv)

		// Go method name: strip "Get" prefix if followed by uppercase letter.
		goMethod := method
		if strings.HasPrefix(method, "Get") && len(method) > 3 && method[3] >= 'A' && method[3] <= 'Z' {
			goMethod = method[3:]
		}

		// Build params and call args (skip first self param).
		var goParams []string
		var callArgs []string
		var settingsKeepAlives []string // param names needing KeepAlive after the cgo call
		usedParamNames := map[string]bool{recvVar: true}
		// First call arg is the receiver handle. For RefCounted non-root types, the handle
		// field holds *C.JPH_Root (e.g. Shape), but cjolt methods expect *C.JPH_X.
		// Cast via unsafe.Pointer to avoid "cannot use *C.JPH_Shape as *C.JPH_ConvexShape".
		if isRefCounted(goRecv) && rootRefCountedType(goRecv) != goRecv {
			callArgs = append(callArgs, fmt.Sprintf("(*cjolt.C_JPH_%s)(unsafe.Pointer(%s.h))", goRecv, recvVar))
		} else {
			callArgs = append(callArgs, recvVar+".h")
		}
		for _, p := range f.Params[1:] {
			rawName := safeParamName(p.Name)
			// Abbreviate long param names in receiver methods only.
			paramName := abbreviateParamName(rawName)
			// Avoid duplicate parameter names: fall back to original name if abbreviation collides.
			if usedParamNames[paramName] {
				paramName = rawName
			}
			// If original name is also taken (e.g. both params named "b"), suffix with index.
			if usedParamNames[paramName] {
				for i := 1; ; i++ {
					candidate := fmt.Sprintf("%s%d", paramName, i)
					if !usedParamNames[candidate] {
						paramName = candidate
						break
					}
				}
			}
			usedParamNames[paramName] = true

			gt, callExpr, keepAlive := methodParamFromCType(p.CType, paramName)
			goParams = append(goParams, paramName+" "+gt)
			callArgs = append(callArgs, callExpr)
			if keepAlive {
				settingsKeepAlives = append(settingsKeepAlives, paramName)
			}
		}

		paramList := strings.Join(goParams, ", ")
		argList := strings.Join(callArgs, ", ")

		// Determine return type and body.
		ret := strings.TrimSpace(f.Return)

		// Check for pointer return: JPH_X* → *X (plain opaque type).
		if ptrGoType, isPtrReturn := parsePointerReturn(ret); isPtrReturn {
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) *%s {\n", recvVar, goRecv, goMethod, paramList, ptrGoType)
			fmt.Fprintf(&b, "    out := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			// RefCounted types have embedded inheritance — use the embedded chain and
			// cast the returned pointer to the root handle type.
			if isRefCounted(ptrGoType) {
				root := rootRefCountedType(ptrGoType)
				chain := buildEmbeddedChain(ptrGoType)
				if root != ptrGoType {
					fmt.Fprintf(&b, "    h := (*cjolt.C_JPH_%s)(unsafe.Pointer(out))\n", root)
					fmt.Fprintf(&b, "    return &%s{%s}\n", ptrGoType, chain)
				} else {
					fmt.Fprintf(&b, "    return &%s{h: out}\n", ptrGoType)
				}
			} else {
				fmt.Fprintf(&b, "    return &%s{h: out}\n", ptrGoType)
			}
			fmt.Fprintf(&b, "}\n\n")
			continue
		}

		// For pointer returns that parsePointerReturn rejected (char*, float*, void*, etc.),
		// skip the method — it needs special handling beyond scope of generated code.
		if strings.HasSuffix(ret, "*") {
			continue
		}

		// Strip const qualifier and JPH_ prefix for scalar return.
		goRet := strings.TrimPrefix(ret, "const ")
		goRet = strings.TrimSpace(goRet)
		goRet = strings.TrimPrefix(goRet, "JPH_")
		// Apply special name mappings (C name after stripping JPH_ → Go name).
		switch goRet {
		case "RMat4":
			goRet = "RMat44"
		case "Mat4":
			goRet = "Mat44"
		}
		// Map C scalar types to Go-native types.
		if mapped, ok := map[string]string{
			"uint8_t": "uint8", "uint16_t": "uint16", "uint32_t": "uint32", "uint64_t": "uint64",
			"int8_t": "int8", "int16_t": "int16", "int32_t": "int32", "int64_t": "int64",
			"float": "float32", "double": "float64", "bool": "bool", "_Bool": "bool",
			"int": "int32", "unsigned int": "uint32",
		}[goRet]; ok {
			goRet = mapped
		}

		if ret == "void" {
			// No return value.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) {\n", recvVar, goRecv, goMethod, paramList)
			fmt.Fprintf(&b, "    cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "}\n\n")
		} else if mathReturnTypes[goRet] {
			// Math type: use unsafe.Pointer cast.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    out := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return *(*%s)(unsafe.Pointer(&out))\n", goRet)
			fmt.Fprintf(&b, "}\n\n")
		} else {
			// Scalar or other return: direct return with explicit type conversion.
			// Required because cjolt may return C._Ctype_JPH_BodyID etc. which isn't
			// directly assignable to Go uint32/BodyID even though layout-compatible.
			fmt.Fprintf(&b, "func (%s *%s) %s(%s) %s {\n", recvVar, goRecv, goMethod, paramList, goRet)
			fmt.Fprintf(&b, "    result := cjolt.%s(%s)\n", f.Name, argList)
			for _, ka := range settingsKeepAlives {
				fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", ka)
			}
			fmt.Fprintf(&b, "    runtime.KeepAlive(%s)\n", recvVar)
			fmt.Fprintf(&b, "    return %s(result)\n", goRet)
			fmt.Fprintf(&b, "}\n\n")
		}
	}
	return b.String()
}
